use std::{
    fs,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result};
use utoipa::OpenApi;

use super::doc_groups::{IdentityApiDoc, OperationsApiDoc, RoutingApiDoc};

const GENERATED_HEADER: &str = "# Generated by `cargo run -- openapi export`. DO NOT EDIT.\n";

#[derive(OpenApi)]
#[openapi(info(
    title = "prompt-ferry Admin API",
    version = "0.1.0",
    description = "Generated admin API snapshot exported from Rust handlers."
))]
struct RootApiDoc;

fn admin_api_doc() -> utoipa::openapi::OpenApi {
    let mut api = RootApiDoc::openapi();
    api.merge(IdentityApiDoc::openapi());
    api.merge(RoutingApiDoc::openapi());
    api.merge(OperationsApiDoc::openapi());
    api
}

pub fn export_admin_api(out: &str) -> Result<()> {
    let out_path = PathBuf::from(out);
    let parent = out_path
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent).with_context(|| {
        format!(
            "failed to create OpenAPI output directory {}",
            parent.display()
        )
    })?;

    let yaml = admin_api_doc()
        .to_yaml()
        .context("failed to serialize OpenAPI document to yaml")?;
    fs::write(&out_path, format!("{GENERATED_HEADER}{yaml}"))
        .with_context(|| format!("failed to write {}", out_path.display()))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::admin_api_doc;

    use utoipa::openapi::{PathItem, path::Operation};

    /// The operation a documented path carries for `method`.
    fn operation<'a>(item: &'a PathItem, method: &str) -> Option<&'a Operation> {
        match method {
            "get" => item.get.as_ref(),
            "post" => item.post.as_ref(),
            "patch" => item.patch.as_ref(),
            "put" => item.put.as_ref(),
            other => panic!("unsupported method {other}"),
        }
    }

    /// The checked-in spec must be exactly what this exporter produces.
    ///
    /// The file carries a `DO NOT EDIT` header, so anything other than a fresh
    /// export is a hand edit that a later export will silently drop. Asserting
    /// byte identity here is what makes "regenerate, do not edit" enforceable
    /// rather than a convention.

    /// The callback is a query-bearing redirect endpoint: `server_id` is the
    /// only required path parameter and the authorization response values are
    /// optional query parameters. Byte parity alone cannot prove this.
    #[test]
    fn mcp_oauth_callback_parameters_are_optional_query_parameters() {
        use utoipa::openapi::Required;
        use utoipa::openapi::path::ParameterIn;

        let document = admin_api_doc();
        let item = document
            .paths
            .paths
            .get("/api/v1/admin/mcp-servers/{server_id}/oauth/callback")
            .expect("the OAuth callback path is documented");
        let operation = operation(item, "get").expect("the callback is a GET");
        let parameters = operation
            .parameters
            .as_ref()
            .expect("the callback documents its parameters");

        let server_id = parameters
            .iter()
            .find(|parameter| parameter.name == "server_id")
            .expect("server_id parameter");
        assert!(
            server_id.parameter_in == ParameterIn::Path,
            "server_id must be a path parameter"
        );
        assert!(
            server_id.required == Required::True,
            "server_id is a required path parameter"
        );

        for name in ["code", "state", "iss"] {
            let parameter = parameters
                .iter()
                .find(|parameter| parameter.name == name)
                .unwrap_or_else(|| panic!("{name} parameter"));
            assert!(
                parameter.parameter_in == ParameterIn::Query,
                "{name} must be a query parameter"
            );
            assert!(
                parameter.required == Required::False,
                "{name} must stay optional"
            );
        }
    }

    #[test]
    fn setup_and_node_contract_is_exported() {
        let document = admin_api_doc();
        for (path, method) in [
            ("/api/v1/auth/setup", "get"),
            ("/api/v1/auth/setup", "post"),
            ("/api/v1/node", "get"),
        ] {
            let item = document.paths.paths.get(path).expect("path is exported");
            assert!(operation(item, method).is_some(), "{method} {path}");
        }
        let schemas = &document.components.as_ref().expect("components").schemas;
        for name in [
            "SetupStatus",
            "SetupRequest",
            "NodeStatusResponse",
            "NodePeerSummary",
        ] {
            assert!(schemas.contains_key(name), "missing {name}");
        }
    }

    #[test]
    fn removed_host_apis_are_not_exported() {
        let document = admin_api_doc();
        let paths = &document.paths.paths;
        assert!(paths.contains_key("/api/v1/admin/nodes"));
        assert!(!paths.contains_key("/api/v1/admin/workers"));
        assert!(!paths.keys().any(|path| path.starts_with("/api/v1/relay/")));
    }
}
