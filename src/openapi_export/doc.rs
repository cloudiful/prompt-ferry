use std::{
    fs::{self, OpenOptions},
    io::Write,
    path::{Path, PathBuf},
};

use anyhow::{Context, Result};
use utoipa::OpenApi;

use super::doc_groups::{IdentityApiDoc, OperationsApiDoc, RoutingApiDoc};

const GENERATED_HEADER: &str = "# Generated by `cargo run -- openapi export`. DO NOT EDIT.\n";

#[derive(OpenApi)]
#[openapi(info(
    title = "prompt-ferry Admin API",
    version = "0.1.0",
    description = "Generated admin API snapshot exported from Rust handlers."
))]
struct RootApiDoc;

fn admin_api_doc() -> utoipa::openapi::OpenApi {
    let mut api = RootApiDoc::openapi();
    api.merge(IdentityApiDoc::openapi());
    api.merge(RoutingApiDoc::openapi());
    api.merge(OperationsApiDoc::openapi());
    api
}

fn write_yaml(document: &utoipa::openapi::OpenApi, out: &Path) -> Result<()> {
    let parent = out
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    let parent = fs::canonicalize(parent)
        .with_context(|| format!("failed to resolve {}", parent.display()))?;
    let destination = parent.join(out.file_name().context("missing YAML output filename")?);
    let yaml = document
        .to_yaml()
        .context("failed to serialize OpenAPI document to yaml")?;
    let temp = parent.join(format!(".openapi-{}.tmp", uuid::Uuid::new_v4()));
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temp)
        .with_context(|| format!("failed to create {}", temp.display()))?;
    let result = (|| -> Result<()> {
        file.write_all(format!("{GENERATED_HEADER}{yaml}").as_bytes())?;
        drop(file);
        fs::rename(&temp, &destination)?;
        Ok(())
    })();
    if let Err(error) = result {
        return match fs::remove_file(&temp) {
            Ok(()) => Err(error.context(format!("failed to write {}", destination.display()))),
            Err(cleanup) => Err(error.context(format!(
                "failed to write {}; cleanup of {} failed: {cleanup}",
                destination.display(),
                temp.display()
            ))),
        };
    }
    Ok(())
}

pub fn export_admin_api(out: &str) -> Result<()> {
    let out_path = PathBuf::from(out);
    let parent = out_path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent).with_context(|| {
        format!(
            "failed to create OpenAPI output directory {}",
            parent.display()
        )
    })?;
    write_yaml(&admin_api_doc(), &out_path)
}

pub fn export_standard_openapi(output: &Path) -> Result<()> {
    let root = fs::canonicalize(".").context("failed to resolve workspace root")?;
    let yaml_parent =
        fs::canonicalize(root.join("openapi")).context("failed to resolve OpenAPI directory")?;
    anyhow::ensure!(
        yaml_parent.starts_with(&root),
        "OpenAPI directory is outside workspace"
    );
    let document = admin_api_doc();
    let json = serde_json::to_string_pretty(&document)
        .context("failed to serialize OpenAPI document to JSON")?;
    let parent = output
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent).with_context(|| format!("failed to create {}", parent.display()))?;
    fs::write(output, json).with_context(|| format!("failed to write {}", output.display()))?;
    write_yaml(&document, &yaml_parent.join("admin-api.yaml"))
}

#[cfg(test)]
mod tests {
    use super::admin_api_doc;

    use utoipa::openapi::{PathItem, RefOr, path::Operation};

    /// The operation a documented path carries for `method`.
    fn operation<'a>(item: &'a PathItem, method: &str) -> Option<&'a Operation> {
        match method {
            "get" => item.get.as_ref(),
            "post" => item.post.as_ref(),
            "patch" => item.patch.as_ref(),
            "put" => item.put.as_ref(),
            other => panic!("unsupported method {other}"),
        }
    }

    /// The checked-in spec must be exactly what this exporter produces.
    ///
    /// The file carries a `DO NOT EDIT` header, so anything other than a fresh
    /// export is a hand edit that a later export will silently drop. Asserting
    /// byte identity here is what makes "regenerate, do not edit" enforceable
    /// rather than a convention.
    /// The callback is a query-bearing redirect endpoint: `server_id` is the
    /// only required path parameter and the authorization response values are
    /// optional query parameters. Byte parity alone cannot prove this.
    #[test]
    fn mcp_oauth_callback_parameters_are_optional_query_parameters() {
        use utoipa::openapi::Required;
        use utoipa::openapi::path::{Parameter, ParameterIn};

        let document = admin_api_doc();
        let item = document
            .paths
            .paths
            .get("/api/v1/admin/mcp-servers/{server_id}/oauth/callback")
            .expect("the OAuth callback path is documented");
        let operation = operation(item, "get").expect("the callback is a GET");
        let parameters = operation
            .parameters
            .as_ref()
            .expect("the callback documents its parameters");

        let parameters: Vec<&Parameter> = parameters
            .iter()
            .map(|parameter| match parameter {
                RefOr::T(parameter) => parameter,
                RefOr::Ref(_) => panic!(
                    "expected an inline parameter, found a $ref; the exporter fixture must not emit references"
                ),
            })
            .collect();

        let server_id = parameters
            .iter()
            .find(|parameter| parameter.name == "server_id")
            .expect("server_id parameter");
        assert!(
            server_id.parameter_in == ParameterIn::Path,
            "server_id must be a path parameter"
        );
        assert!(
            server_id.required == Required::True,
            "server_id is a required path parameter"
        );

        for name in ["code", "state", "iss"] {
            let parameter = parameters
                .iter()
                .find(|parameter| parameter.name == name)
                .unwrap_or_else(|| panic!("{name} parameter"));
            assert!(
                parameter.parameter_in == ParameterIn::Query,
                "{name} must be a query parameter"
            );
            assert!(
                parameter.required == Required::False,
                "{name} must stay optional"
            );
        }
    }

    #[test]
    fn setup_and_node_contract_is_exported() {
        let document = admin_api_doc();
        for (path, method) in [
            ("/api/v1/auth/setup", "get"),
            ("/api/v1/auth/setup", "post"),
            ("/api/v1/node", "get"),
        ] {
            let item = document.paths.paths.get(path).expect("path is exported");
            assert!(operation(item, method).is_some(), "{method} {path}");
        }
        let schemas = &document.components.as_ref().expect("components").schemas;
        for name in [
            "SetupStatus",
            "SetupRequest",
            "NodeStatusResponse",
            "NodePeerSummary",
        ] {
            assert!(schemas.contains_key(name), "missing {name}");
        }
    }

    #[test]
    fn removed_host_apis_are_not_exported() {
        let document = admin_api_doc();
        let paths = &document.paths.paths;
        assert!(paths.contains_key("/api/v1/admin/nodes"));
        assert!(!paths.contains_key("/api/v1/admin/workers"));
        assert!(!paths.keys().any(|path| path.starts_with("/api/v1/relay/")));
    }

    /// Assert one serialized response object carries the OAS-required
    /// non-empty `description`. A `$ref` is resolved through
    /// `components.responses`; an unresolved or external reference fails with
    /// the reference instead of being skipped.
    fn assert_response_description(
        document: &serde_json::Value,
        location: &str,
        response: &serde_json::Value,
    ) {
        if let Some(reference) = response.get("$ref") {
            let reference = reference
                .as_str()
                .unwrap_or_else(|| panic!("{location}: response $ref must be a string"));
            let name = reference
                .strip_prefix("#/components/responses/")
                .unwrap_or_else(|| {
                    panic!("{location}: unsupported response reference {reference}")
                });
            let resolved = document
                .get("components")
                .and_then(|components| components.get("responses"))
                .and_then(|responses| responses.get(name))
                .unwrap_or_else(|| panic!("{location}: unresolved response reference {reference}"));
            assert_response_description(document, location, resolved);
            return;
        }
        let description = response
            .get("description")
            .unwrap_or_else(|| panic!("{location}: response object has no description"));
        let description = description
            .as_str()
            .unwrap_or_else(|| panic!("{location}: response description is not a string"));
        assert!(
            !description.trim().is_empty(),
            "{location}: response description must not be empty"
        );
    }

    /// OAS 3.1 requires every Response Object to carry a description, and
    /// utoipa 6 omits an empty one at serialization time. Assert the serialized
    /// document so a future regression is caught even if the typed field
    /// exists.
    #[test]
    fn every_serialized_response_object_carries_a_non_empty_description() {
        let document = admin_api_doc();
        let value = serde_json::to_value(&document).expect("the admin document serializes to JSON");

        let paths = value
            .get("paths")
            .and_then(|paths| paths.as_object())
            .expect("the serialized document has a paths object");
        for (path, item) in paths {
            let methods = item
                .as_object()
                .unwrap_or_else(|| panic!("{path}: path item is not an object"));
            for (method, operation) in methods {
                if !matches!(
                    method.as_str(),
                    "get" | "put" | "post" | "delete" | "options" | "head" | "patch" | "trace"
                ) {
                    continue;
                }
                let responses = operation
                    .get("responses")
                    .and_then(|responses| responses.as_object())
                    .unwrap_or_else(|| {
                        panic!("{method} {path}: operation has no responses object")
                    });
                for (status, response) in responses {
                    assert_response_description(
                        &value,
                        &format!("{method} {path} {status}"),
                        response,
                    );
                }
            }
        }

        if let Some(responses) = value
            .get("components")
            .and_then(|components| components.get("responses"))
            .and_then(|responses| responses.as_object())
        {
            for (name, response) in responses {
                assert_response_description(
                    &value,
                    &format!("components.responses.{name}"),
                    response,
                );
            }
        }
    }
}
